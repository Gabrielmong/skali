import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { ConfigForm } from './ConfigForm.tsx'
import { FIELDS } from './fixtures.ts'

describe('ConfigForm', () => {
  it('renders switch/number/select/secret/text from types; locked field is disabled and shows its note', () => {
    render(<ConfigForm fields={FIELDS} edits={{}} onChange={() => {}} />)
    expect(screen.getByRole('switch', { name: 'PvP' })).toBeChecked()
    expect(screen.getByRole('spinbutton', { name: 'Port' })).toHaveValue(25565)
    expect(screen.getByRole('combobox', { name: 'Difficulty' })).toHaveTextContent('easy')
    expect(screen.getByLabelText('RCON password')).toHaveAttribute('type', 'password')
    expect(screen.getByRole('textbox', { name: 'Message of the day' })).toHaveValue('Welcome')
    expect(screen.getByText('Shown in the server list')).toBeInTheDocument()
    expect(screen.getByRole('textbox', { name: 'World seed' })).toBeDisabled()
    expect(screen.getByText('Changing the seed needs a new world')).toBeInTheDocument()
    expect(screen.getByText('Gameplay')).toBeInTheDocument()
    expect(screen.getByText('Network')).toBeInTheDocument()
  })

  it('reveals a secret with the show icon', async () => {
    render(<ConfigForm fields={FIELDS} edits={{}} onChange={() => {}} />)
    await userEvent.click(screen.getByRole('button', { name: 'Show RCON password' }))
    expect(screen.getByLabelText('RCON password')).toHaveAttribute('type', 'text')
  })

  it('filter hides non-matching fields', async () => {
    render(<ConfigForm fields={FIELDS} edits={{}} onChange={() => {}} />)
    await userEvent.type(screen.getByRole('textbox', { name: 'Filter settings' }), 'DIFFI')
    expect(screen.getByRole('combobox', { name: 'Difficulty' })).toBeInTheDocument()
    expect(screen.queryByRole('switch', { name: 'PvP' })).toBeNull()
    expect(screen.queryByRole('spinbutton', { name: 'Port' })).toBeNull()
  })

  it('filter also matches help text', async () => {
    render(<ConfigForm fields={FIELDS} edits={{}} onChange={() => {}} />)
    await userEvent.type(screen.getByRole('textbox', { name: 'Filter settings' }), 'server list')
    expect(screen.getByRole('textbox', { name: 'Message of the day' })).toBeInTheDocument()
    expect(screen.queryByRole('textbox', { name: 'World seed' })).toBeNull()
  })

  it('reports edits by id: a boolean for a switch, the typed string for a number', async () => {
    const onChange = vi.fn()
    render(<ConfigForm fields={FIELDS} edits={{}} onChange={onChange} />)
    await userEvent.click(screen.getByRole('switch', { name: 'PvP' }))
    expect(onChange).toHaveBeenCalledWith('pvp', false)
    await userEvent.type(screen.getByRole('spinbutton', { name: 'Port' }), '1')
    expect(onChange).toHaveBeenCalledWith('port', '255651')
  })

  it('an empty or non-numeric number edit shows an error', () => {
    render(<ConfigForm fields={FIELDS} edits={{ port: '' }} onChange={() => {}} />)
    expect(screen.getByText('Enter a number')).toBeInTheDocument()
  })

  it('a locked secret is masked and disabled, and can still be revealed', async () => {
    const fields = [{ id: 'pw', key: 'AdminPassword', value: 'hunter2', type: 'secret' as const, label: 'Admin password', locked: 'Generated by Skáli' }]
    render(<ConfigForm fields={fields} edits={{}} onChange={() => {}} />)
    const input = screen.getByLabelText('Admin password')
    expect(input).toHaveAttribute('type', 'password')
    expect(input).toBeDisabled()
    await userEvent.click(screen.getByRole('button', { name: 'Show Admin password' }))
    expect(screen.getByLabelText('Admin password')).toHaveAttribute('type', 'text')
  })
})
